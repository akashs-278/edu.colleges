#include <iostream>
#include <math.h>
using namespace std;
int main()
{
    double s = 25;
    cout << "Square root value of y=25 is : " << sqrt(s) << endl;
    int z = -10;
    cout << "Absolute value of z:-10 is : " << abs(z) << endl;
    int x = 12, y = 2;
    cout << "Power value: x^y = (12^2) is: " << pow(x, y) << endl;

    double m = 2.5;
    cout << "Floor value of x=2.5 is : " << floor(m) << endl;
    double n = 2.5;
    cout << "Ceiling value of y=2.5 is : " << ceil(n) << endl;
    return 0;
}